#!/usr/bin/env node
/**
 * Post-build: keep every legacy URL working on the static export.
 *
 * 1. Writes a tiny redirect page (meta refresh + canonical + JS) at each old
 *    path inside dist/. Paths like /business/default.aspx are written as
 *    dist/business/default.aspx/index.html — static hosts serve that for the
 *    bare URL (or after a trailing-slash hop), and it avoids hosts serving a
 *    ".aspx" file with the wrong MIME type.
 * 2. Writes real 301 rules for the hosting provider:
 *      dist/_redirects  (Netlify / Cloudflare Pages)
 *      dist/.htaccess   (Apache / most cPanel hosts)
 *    and REDIRECTS.md (human-readable list + Vercel/nginx snippets).
 *
 * Runs automatically via the "postbuild" npm script.
 */
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "dist");
const SITE = "https://www.businessinsurancewashingtondc.com";

/** Legacy coverage URLs → slugs. Kept in sync with content.ts (legacyPaths). */
async function coverageMap() {
  const src = await readFile(path.join(ROOT, "src/data/content.ts"), "utf8");
  const map = [];
  const re = /slug: "([^"]+)",[\s\S]*?legacyPaths: \[([^\]]*)\]/g;
  for (const m of src.matchAll(re)) {
    for (const p of m[2].matchAll(/"([^"]+)"/g)) map.push([p[1], `/coverage/${m[1]}/`]);
  }
  return map;
}

const STATIC = [
  ["/default.aspx", "/"],
  ["/index.aspx", "/"],
  ["/about/", "/#about"],
  ["/about.aspx", "/#about"],
  ["/about/default.aspx", "/#about"],
  ["/content/artres.aspx", "/about/arthur-lander/"],
  ["/contact/", "/#contact"],
  ["/contact.aspx", "/#contact"],
  ["/newsletter.aspx", "/newsletter/"],
  ["/refer.aspx", "/refer/"],
  ["/privacy.aspx", "/privacy/"],
  ["/partners/", "/#independent"],
  ["/carriers/", "/#independent"],
  ["/carriers/default.aspx", "/#independent"],
  ["/m/", "/"],
  ["/es-us/", "/"],
  ...[..."abcdefghijklmnopqrstuvwxyz"].map((l) => [`/glossary/${l}/`, `/glossary/#${l}`]),
];

const esc = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

function stub(to, js = "") {
  const abs = SITE + to;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Redirecting… | Value Insurance Agency Inc.</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="${esc(abs)}">
<meta http-equiv="refresh" content="0; url=${esc(to)}">
<script>${js || `location.replace(${JSON.stringify(to)});`}</script>
<style>body{font:16px/1.6 system-ui,sans-serif;background:#f5f3ee;color:#221f1f;display:grid;place-items:center;min-height:100vh;margin:0}a{color:inherit}</style>
</head>
<body><p>This page has moved to <a href="${esc(to)}">${esc(abs)}</a>.</p></body>
</html>
`;
}

/** Where a legacy URL's stub lives inside dist/. */
function stubFile(from) {
  return path.join(OUT, from.split("?")[0], "index.html");
}

async function main() {
  if (!existsSync(OUT)) throw new Error("dist/ not found — run `next build` first");
  const coverage = await coverageMap();
  const all = [...STATIC, ...coverage];
  const plain = all.filter(([from]) => !from.includes("?"));
  const query = all.filter(([from]) => from.includes("?"));

  let written = 0;
  for (const [from, to] of plain) {
    const file = stubFile(from);
    if (existsSync(file)) continue; // never overwrite a real page
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, stub(to));
    written++;
  }

  // /category.aspx?id=… — one stub that picks the target from the query string.
  const byId = Object.fromEntries(query.map(([from, to]) => [new URLSearchParams(from.split("?")[1]).get("id"), to]));
  const catFile = path.join(OUT, "category.aspx", "index.html");
  await mkdir(path.dirname(catFile), { recursive: true });
  await writeFile(
    catFile,
    stub("/#coverage", `var m=${JSON.stringify(byId)};var id=(new URLSearchParams(location.search).get("id")||"").toUpperCase();location.replace(m[id]||"/#coverage");`),
  );
  written++;

  // ---- host rules (real 301s) ----
  const netlify = [
    "# Legacy URLs → new pages (Netlify / Cloudflare Pages). Generated by scripts/redirects.mjs",
    ...query.map(([from, to]) => {
      const [p, q] = from.split("?");
      return `${p}  ${q}  ${to}  301!`;
    }),
    ...plain.map(([from, to]) => `${from}  ${to}  301!`),
    ...plain.filter(([f]) => f.endsWith(".aspx")).map(([from, to]) => `${from}/  ${to}  301!`),
  ].join("\n");
  await writeFile(path.join(OUT, "_redirects"), netlify + "\n");

  const htaccess = [
    "# Legacy URLs → new pages (Apache). Generated by scripts/redirects.mjs",
    "RewriteEngine On",
    ...query.map(([from, to]) => {
      const [p, q] = from.split("?");
      return `RewriteCond %{QUERY_STRING} (^|&)${q.replace("=", "=")}(&|$) [NC]\nRewriteRule ^${p.slice(1).replace(/\./g, "\\.")}$ ${to.replace("#", "\\#")} [R=301,L,QSD,NE]`;
    }),
    ...plain.map(([from, to]) => `RewriteRule ^${from.slice(1).replace(/\./g, "\\.").replace(/\/$/, "/?")}$ ${to.replace("#", "\\#")} [R=301,L,NE]`),
    "ErrorDocument 404 /404.html",
  ].join("\n");
  await writeFile(path.join(OUT, ".htaccess"), htaccess + "\n");

  // `serve` (npm run serve) reads dist/serve.json — mirror the 301s so local testing matches production.
  const serveJson = {
    directoryListing: false,
    trailingSlash: true,
    redirects: [
      ...plain.map(([from, to]) => ({ source: from.replace(/\/$/, ""), destination: to, type: 301 })),
      ...plain.filter(([f]) => f.endsWith(".aspx")).map(([from, to]) => ({ source: `${from}/`, destination: to, type: 301 })),
    ],
  };
  await writeFile(path.join(OUT, "serve.json"), JSON.stringify(serveJson, null, 2));

  const md = [
    "# Legacy URL redirects",
    "",
    "Generated by `scripts/redirects.mjs` on every `npm run build`.",
    "",
    "The static export already contains a redirect page at every old path (meta refresh + canonical),",
    "so old links work on any host. For SEO, also configure real **301** redirects at the host:",
    "",
    "- **Netlify / Cloudflare Pages:** `dist/_redirects` is picked up automatically (Cloudflare ignores the query-string rules; the `/category.aspx` stub handles those).",
    "- **Apache / cPanel:** `dist/.htaccess` is included.",
    "- **Nginx on Lightsail (`cpanel sites new`):** run `sudo bash deploy/fix-nginx.sh <domain>` once. It makes the old `.aspx` addresses open the redirect pages in `dist/`.",
    "- **Vercel / nginx:** copy the table below into `vercel.json` `redirects` or `location` blocks.",
    "",
    "| Old URL | New URL |",
    "|---|---|",
    ...all.map(([from, to]) => `| \`${from}\` | \`${to}\` |`),
    "",
  ].join("\n");
  await writeFile(path.join(ROOT, "REDIRECTS.md"), md);

  console.log(`Redirects: ${all.length} legacy URLs, ${written} stub pages written, _redirects + .htaccess + serve.json + REDIRECTS.md generated.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
